type TranslationKey = keyof typeof dictionary.zh;

export function translate(locale: Locale, key: TranslationKey, values?: Record<string, Primitive>) {
  let text: string = dictionary[locale][key] ?? dictionary.zh[key] ?? key;
  if (!values) return text;
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll(`{${name}}`, String(value ?? ""));
  }
  return text;
}

export type TFunction = typeof translate;

export function localeTag(locale: Locale) {
  return locale === "zh" ? "zh-CN" : "en-US";
}

export function formatDateTime(locale: Locale, value: string | number | Date) {
  return new Date(value).toLocaleString(localeTag(locale), { hour12: false });
}

export function formatTime(locale: Locale, value: string | number | Date) {
  return new Date(value).toLocaleTimeString(localeTag(locale), { hour12: false });
}
