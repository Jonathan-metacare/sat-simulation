type TranslationKey = keyof typeof dictionary.zh;

export function translate(locale: Locale, key: TranslationKey, values?: Record<string, Primitive>) {
  let text: string = dictionary[locale][key] ?? dictionary.zh[key] ?? key;
  if (!values) return text;
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll(`{${name}}`, String(value ?? ""));
  }
  return text;
}

export type TFunction = typeof translate;
